# CLI
# ---------------------------------------------------------------------------

def _parse_int_list(text, name):
    try:
        vals = [int(x) for x in text.split(",")]
    except ValueError:
        raise SystemExit("%s must be a comma list of ints, got %r"
                         % (name, text))
    if not vals:
        raise SystemExit("%s must not be empty" % name)
    return vals


def _parse_seeds(text):
    try:
        a, b = text.split(":", 1)
        a, b = int(a), int(b)
    except ValueError:
        raise SystemExit("--seeds must be A:B (half-open range), got %r"
                         % text)
    if b <= a:
        raise SystemExit("--seeds needs A < B, got %r" % text)
    return range(a, b)


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="W-msg message-multiset conservation harness "
                    "(docs/kernel-fuzzing-design.md §7.3)")
    ap.add_argument("--seeds", required=True, metavar="A:B",
                    help="half-open seed range A..B-1")
    ap.add_argument("--k", default="4", metavar="K[,K...]",
                    help="worker count(s), comma list (default 4)")
    ap.add_argument("--m", default="25", metavar="M[,M...]",
                    help="messages per worker, comma list (default 25)")
    ap.add_argument("--jobs", type=int, default=None, metavar="J",
                    help="parallel cases (default min(8, cpus))")
    ap.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT,
                    help="per-case timeout seconds (default 10)")
    ap.add_argument("--tinyactor", default=TINYACTOR, metavar="PATH",
                    help="binary under test (default repo ./tinyactor)")
    ap.add_argument("--findings-dir", default=DEFAULT_FINDINGS_DIR,
                    metavar="DIR", help="finding evidence directory")
    args = ap.parse_args(argv)

    seeds = _parse_seeds(args.seeds)
    ks = _parse_int_list(args.k, "--k")
    ms = _parse_int_list(args.m, "--m")
    for k in ks:
        for m in ms:
            _check_km(k, m)

    summary = run_matrix(seeds, ks, ms, jobs=args.jobs,
                         timeout=args.timeout, tinyactor=args.tinyactor,
                         findings_dir=args.findings_dir)
    print_summary(summary)
    if args.findings_dir == DEFAULT_FINDINGS_DIR:
        print("findings dir: %s" % args.findings_dir, file=sys.stderr)
    return 0 if summary["n_cases"] == summary["conserved"] else 1


if __name__ == "__main__":
    sys.exit(main())