# W-chaos: spawn/death high frequency (§7.4 TSan long-run)
# ---------------------------------------------------------------------------

def gen_chaos(seed, scale):
    """Emit a W-chaos workload: R rounds x C short-lived leaves per round.

    Per round main spawns C leaves, monitors each, waits for exactly C
    DOWN messages, then prints one "round <r>" line.  Leaf behaviors are
    seed-chosen per slot from a config table (first message):
      alloc n  — build-and-discard an n-cell list (alloc churn)
      sub      — spawn one nested child and wait for its DOWN
      die      — die by divzero crash (exercises the crash/death path;
                 monitor still delivers DOWN, other actors unaffected —
                 probed before use, see .pge/progress.md task-workloads)

    Output: one deterministic line per round + a final "done <R>" line —
    a TSan hang/deadlock shows up as missing lines / timeout, not garbled
    text.  Scale R for 30min-class long runs (§7.4 nightly).
    """
    _check_scale(scale)
    p = prng.make_prng(seed)

    rounds = 50 * scale + p.next_range(10)
    c = min(32, 4 + p.next_range(4))
    # per-slot leaf configs: [alloc_n, sub?, die?] — at least one slot
    # dies and one spawns a sub-child per round when C >= 2
    slots = []
    for j in range(c):
        alloc_n = 50 + p.next_range(451)
        sub = (j % 3 == 1)
        die = (j % 4 == 3)
        slots.append((alloc_n, sub, die))
    if c >= 2 and not any(d for (_, _, d) in slots):
        slots[c // 2] = (slots[c // 2][0], slots[c // 2][1], True)

    lines = [_header("W-chaos", seed, scale,
                     "rounds=%d C=%d" % (rounds, c))]
    lines.append("import str\n")

    lines.append("""\
fn build(n, acc) {
  if n == 0 {
    acc
  } else {
    build(n - 1, cons(n, acc))
  }
}

// leaf: first message = [alloc_n, sub, die]; dies by crash or returns
fn leaf() {
  let cfg = recv()
  let n = car(cfg)
  let sub = car(cdr(cfg))
  let die = car(cdr(cdr(cfg)))
  let junk = build(n, nil)
  if die {
    let z = n - n
    let boom = n / z
    0
  } else {
    if sub {
      let child = spawn('leaf)
      let ref = monitor(child)
      send(child, [1, false, false])
      let down2 = recv()
      junk
    } else {
      junk
    }
  }
}
""")

    lines.append("""\
fn wait_downs(i, c) {
  if i == c {
    0
  } else {
    let down = recv()
    wait_downs(i + 1, c)
  }
}

fn spawn_leaves(r, rounds, c, j, tbl) {
  if j == c {
    wait_downs(0, c)
    print(str.concat("round ", str.from_int(r)))
    rounds_loop(r + 1, rounds, c, tbl)
  } else {
    let pid = spawn('leaf)
    let ref = monitor(pid)
    send(pid, nth(tbl, j))
    spawn_leaves(r, rounds, c, j + 1, tbl)
  }
}

fn rounds_loop(r, rounds, c, tbl) {
  if r == rounds {
    print(str.concat("done ", str.from_int(r)))
  } else {
    spawn_leaves(r, rounds, c, 0, tbl)
  }
}
""")

    def lit_bool(b):
        return "true" if b else "false"

    slot_lits = ["[%d, %s, %s]"
                 % (n, lit_bool(s), lit_bool(d)) for (n, s, d) in slots]
    tbl = "[" + ", ".join(slot_lits) + "]"
    lines.append("fn nth(lst, n) {")
    lines.append("  if n == 0 {")
    lines.append("    car(lst)")
    lines.append("  } else {")
    lines.append("    nth(cdr(lst), n - 1)")
    lines.append("  }")
    lines.append("}\n")
    lines.append("fn main() {")
    lines.append("  rounds_loop(0, %d, %d, %s)" % (rounds, c, tbl))
    lines.append("}\n")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# dispatch / CLI / smoke
# ---------------------------------------------------------------------------

_GENERATORS = {
    "pure": gen_pure,
    "msg": gen_msg,
    "chaos": gen_chaos,
}


def generate(kind, seed, scale=1):
    """Generate one workload's .ta source (deterministic in all args)."""
    if kind not in _GENERATORS:
        raise ValueError("kind must be one of %s, got %r"
                         % ("/".join(KINDS), kind))
    if not (0 <= seed < (1 << 64)):
        raise ValueError("seed must be in [0, 2^64)")
    return _GENERATORS[kind](seed, _check_scale(scale))


def run_smoke(text, timeout=300):
    """Build+run `text` via ./tinyactor; return (returncode, stdout, stderr).

    Skips (returns None) when ./tinyactor is not built so the unit test
    suite degrades gracefully on a bare checkout.
    """
    if not os.path.exists(TINYACTOR):
        return None
    with tempfile.NamedTemporaryFile(
            "w", suffix=".ta", delete=False) as f:
        f.write(text)
        path = f.name
    try:
        proc = subprocess.run(
            [TINYACTOR, "run", path],
            capture_output=True, timeout=timeout)
        return proc.returncode, proc.stdout, proc.stderr
    finally:
        os.unlink(path)


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Generate a GC-hostile TA workload "
                    "(docs/kernel-fuzzing-design.md §7.0-7.4)")
    ap.add_argument("--kind", required=True, choices=KINDS,
                    help="pure: sequential diff / msg: multiset harness / "
                         "chaos: TSan long-run")
    ap.add_argument("--seed", required=True, type=int,
                    help="PRNG seed (u64, M-2 counter-based sha256 stream)")
    ap.add_argument("--scale", type=int, default=1,
                    help="allocation/scale multiplier (>= 1)")
    ap.add_argument("--smoke", action="store_true",
                    help="after generating, build+run via ./tinyactor and "
                         "exit nonzero on failure (generator self-check)")
    args = ap.parse_args(argv)

    text = generate(args.kind, args.seed, args.scale)
    if args.smoke:
        res = run_smoke(text)
        if res is None:
            print("gc-workloads-SKIPPED: ./tinyactor not built", file=sys.stderr)
            return 0
        rc, out, err = res
        ok = rc == 0 and len(out) > 0
        if not ok:
            sys.stdout.write(text)
            print("gc-workloads-SMOKE-FAIL: rc=%d stdout=%dB stderr=%s"
                  % (rc, len(out), err.decode("utf-8", "replace")[:2000]),
                  file=sys.stderr)
            return 1
        print("gc-workloads-SMOKE-OK: kind=%s seed=%d scale=%d rc=0 stdout=%dB"
              % (args.kind, args.seed, args.scale, len(out)), file=sys.stderr)
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())