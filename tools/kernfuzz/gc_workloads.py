# W-msg: multi-actor message churn (§7.3 multiset harness)
# ---------------------------------------------------------------------------

def gen_msg(seed, scale):
    """Emit a W-msg workload: K workers x M messages -> "<wid> <seq>" lines.

    First-message configuration pattern (R3: spawn is zero-arg ONLY):
      spawn('worker); send(w, [cp, wid, m, plen])  ->  worker recv()s it.
    The collector likewise gets [K*M] as its first message, and main ends
    with monitor(cp) + recv() so the program terminates only after the
    collector has drained every message.

    Each message payload embeds a freshly built deep list (plen cons
    cells); send deep-copies it and the collector drops it — deep-structure
    churn across send boundaries, the §7.3 "跨 send 共享/深结构载荷" shape.
    Output is exactly K*M lines "<wid> <seq>", unsorted (the harness sorts).
    """
    _check_scale(scale)
    p = prng.make_prng(seed)

    k = min(16, 2 + scale) + p.next_range(2)
    m = 25 * scale + p.next_range(10)
    base_plen = 50 + p.next_range(50)
    total = k * m

    lines = [_header("W-msg", seed, scale,
                     "K=%d M=%d plen_base=%d" % (k, m, base_plen))]
    lines.append("import str\n")

    lines.append("""\
fn collect_loop(i, n) {
  if i == n {
    0
  } else {
    let msg = recv()
    print(str.concat(str.from_int(car(msg)), str.concat(" ", str.from_int(car(cdr(msg))))))
    collect_loop(i + 1, n)
  }
}

// collector: first message = [total]; then drain total messages,
// printing one "<wid> <seq>" line each (no sorting in TA)
fn collector() {
  let cfg = recv()
  collect_loop(0, car(cfg))
}
""")

    lines.append("""\
// fresh deep payload per message: send deep-copies it, collector drops it
fn payload(n, acc) {
  if n == 0 {
    acc
  } else {
    payload(n - 1, cons(n, acc))
  }
}

fn wloop(cp, wid, s, m, plen) {
  if s == m {
    0
  } else {
    send(cp, cons(wid, cons(s, payload(plen, nil))))
    wloop(cp, wid, s + 1, m, plen)
  }
}

// worker: first message = [cp, wid, m, plen] (spawn is zero-arg, R3)
fn worker() {
  let cfg = recv()
  wloop(car(cfg), car(cdr(cfg)), 0, car(cdr(cdr(cfg))), car(cdr(cdr(cdr(cfg)))))
}
""")

    lines.append("fn main() {")
    lines.append("  let cp = spawn('collector)")
    lines.append("  send(cp, cons(%d, nil))" % total)
    for wid in range(k):
        plen = base_plen + p.next_range(10 * scale + 10)
        lines.append("  let w%d = spawn('worker)" % wid)
        lines.append("  send(w%d, cons(cp, cons(%d, cons(%d, cons(%d, nil)))))"
                     % (wid, wid, m, plen))
    lines.append("  let ref = monitor(cp)")
    lines.append("  recv()")
    lines.append("}\n")
    return "\n".join(lines)


