# -*- coding: utf-8 -*-
"""gc_workloads.py — three GC-hostile TA workload generators (Phase 7).

Task: .pge/tasks/task-workloads.md; authoritative design:
docs/kernel-fuzzing-design.md §7.0-7.4 (workload x oracle matrix) + DEC-6
(Python3 stdlib only).

Each generated workload strictly serves ONE oracle (§7.0):

  kind    form                                          feeds
  ------  --------------------------------------------  ----------------------
  pure    single actor, pure allocation (closure        GC sequential diff
          capture-and-discard, deep shared structures,  (§7.2: stress vs
          string churn).  STRICTLY no send/spawn/       normal, compare())
          monitor/recv/receive/self — the generator
          gates the emitted text (§7.0: sequential
          determinism premise).
  msg     multi-actor message churn, deep structures    multiset harness (§7.3)
          inside send payloads; output is one line per
          message "<wid> <seq>" (sorting happens in the
          harness, never in TA).  spawn is zero-arg
          (R3): worker parameters travel as the FIRST
          message, worker recv()s the config before
          entering its work loop.
  chaos   high-frequency spawn/death + message mix;     TSan long-run + timeout
          short-lived processes; per-round output is    detection (§7.4)
          one deterministic line, so a hang shows up
          as a missing line instead of garbled output.

Common:
  * seeded PRNG from tools/kernfuzz/prng.py (M-2, never stdlib random);
    same --seed -> byte-identical program, byte-identical W-pure output.
  * CLI: --kind pure|msg|chaos --seed S --scale N  -> .ta source on stdout.
    --smoke additionally build+runs the generated program via ./tinyactor
    and exits nonzero on failure (generator self-check).
  * TA language gotchas honored (AGENTS.md / kernfuzz gen.py R-rules):
    bool predicates used bare in `if` (no `== 1`), str.concat takes exactly
    2 args, negative int literals rendered as (0 - N) (no unary minus),
    all integer literals within int48.

Language forms used here were probed against the working-tree
parser/typecheck/VM before this generator was written (see
.pge/progress.md task-workloads): tail-recursive list build, non-tail
tree recursion (depth-bounded), closure capture-and-discard,
spawn('name) + first-message config, monitor/recv DOWN barrier, divzero
actor crash (kills only the crashing actor; monitor still delivers DOWN).
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import prng                      # noqa: E402

_REPO = os.path.normpath(os.path.join(_HERE, "..", ".."))
TINYACTOR = os.path.join(_REPO, "tinyactor")

KINDS = ("pure", "msg", "chaos")

# Gate for W-pure (§7.0: "W-pure 严格不含 send/spawn"): no actor primitive
# may appear anywhere in the emitted text, including comments.
PURE_BANNED_RE = re.compile(r"\b(send|spawn|monitor|recv|receive|self)\b")


def assert_no_messaging(text):
    """W-pure gate: raise ValueError if any actor primitive appears.

    This is the load-side guard for the §7.2 sequential-diff oracle: a
    single actor with no messaging keeps normal vs TA_GC_STRESS runs
    deterministic and line-comparable.
    """
    m = PURE_BANNED_RE.search(text)
    if m:
        raise ValueError(
            "W-pure workload must not contain actor primitive %r (§7.0)"
            % m.group(0))


def _check_scale(scale):
    if scale < 1:
        raise ValueError("scale must be >= 1")
    if scale > 1000000:
        raise ValueError("scale must be <= 1000000")
    return scale


def _header(kind, seed, scale, note):
    """Traceability comment. Never contains words banned for W-pure."""
    return ("// gc_workloads %s seed=%d scale=%d %s\n"
            "// generated by tools/kernfuzz/gc_workloads.py — do not edit\n"
            % (kind, seed, scale, note))


# ---------------------------------------------------------------------------
# W-pure: single actor, pure allocation (§7.2 sequential diff)
# ---------------------------------------------------------------------------

def gen_pure(seed, scale):
    """Emit a W-pure workload: deterministic checksum-per-phase program.

    Phases (order seed-chosen; every count seed-jittered and scaled):
      closure  capture-and-discard closures, called once each
      list     deep list build (tail-recursive) + full traversal
      share    short fresh spine consed onto ONE long shared base list
               K times — GC must keep the shared tail alive per spine
      tree     depth-bounded binary tree build + recursive traversal
      str      string churn (fresh str.concat + str.from_int garbage)

    Output: one labeled checksum line per phase.  Deterministic: no
    messaging, no time, no scheduler involvement — so `tavm run` vs
    `TA_GC_STRESS=1 tavm run` must be byte-identical (§7.2).
    """
    _check_scale(scale)
    p = prng.make_prng(seed)

    n_closure = 2000 * scale + p.next_range(500)
    n_list = 20000 * scale + p.next_range(2000)
    share_base_n = 500 + p.next_range(50)
    share_k = 200 * scale + p.next_range(100)
    tree_depth = 8 + p.next_range(5)          # 2^depth nodes, bounded
    n_str = 2000 * scale + p.next_range(500)
    closure_arg = 2 + p.next_range(8)
    filler = chr(97 + p.next_range(26))
    labels = ["closure", "list", "share", "tree", "str"]
    # seeded phase order (stable shuffle via Fisher-Yates on prng draws)
    for i in range(len(labels) - 1, 0, -1):
        j = p.next_range(i + 1)
        labels[i], labels[j] = labels[j], labels[i]

    lines = [_header("W-pure", seed, scale,
                     "single actor / pure allocation / sequential diff")]
    lines.append("import str\n")

    lines.append("""\
fn make_adder(n) {
  fn(x) { x + n }
}

fn closure_churn(n, acc) {
  if n == 0 {
    acc
  } else {
    let f = make_adder(n)
    closure_churn(n - 1, acc + f(%d))
  }
}
""" % closure_arg)

    lines.append("""\
fn build(n, acc) {
  if n == 0 {
    acc
  } else {
    build(n - 1, cons(n, acc))
  }
}

fn sum_list(lst, acc) {
  if null?(lst) {
    acc
  } else {
    sum_list(cdr(lst), acc + car(lst))
  }
}
""")

    lines.append("""\
// fresh 2-cell spine sharing ONE base list as tail; base must survive
// every spine sum or the checksum changes (shared-structure GC trap)
fn share(base, k, acc) {
  if k == 0 {
    acc
  } else {
    let l = cons(0 - 1, cons(0 - 2, base))
    share(base, k - 1, acc + sum_list(l, 0))
  }
}
""")

    lines.append("""\
fn tree(d) {
  if d == 0 {
    1
  } else {
    cons(tree(d - 1), cons(tree(d - 1), nil))
  }
}

fn tree_sum(t) {
  if pair?(t) {
    tree_sum(car(t)) + tree_sum(car(cdr(t)))
  } else {
    t
  }
}
""")

    lines.append("""\
fn strchurn(n, c, acc) {
  if n == 0 {
    acc
  } else {
    let s = str.concat(str.from_int(n), c)
    strchurn(n - 1, c, acc + str.length(s))
  }
}
""")

    # main: phase bodies emitted in the seeded order, each printing one
    # labeled checksum line (every print on its own line)
    lines.append("fn main() {")
    for name in labels:
        if name == "closure":
            lines.append("  print(str.concat(\"closure \","
                         " str.from_int(closure_churn(%d, 0))))"
                         % n_closure)
        elif name == "list":
            lines.append("  let lst = build(%d, nil)" % n_list)
            lines.append("  print(str.concat(\"list \","
                         " str.from_int(sum_list(lst, 0))))")
        elif name == "share":
            lines.append("  let base = build(%d, nil)" % share_base_n)
            lines.append("  print(str.concat(\"share \","
                         " str.from_int(share(base, %d, 0))))" % share_k)
        elif name == "tree":
            lines.append("  print(str.concat(\"tree \","
                         " str.from_int(tree_sum(tree(%d)))))" % tree_depth)
        elif name == "str":
            lines.append("  print(str.concat(\"str \","
                         " str.from_int(strchurn(%d, \"%s\", 0))))"
                         % (n_str, filler))
    lines.append("}\n")
    text = "\n".join(lines)
    assert_no_messaging(text)
    return text


